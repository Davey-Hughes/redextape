/// This tests a REAL difference even though the encoding it contrasts against (`Unary`) is not the TM
/// backend's only option. See `the_tm_reports_its_ceiling_on_the_same_demos` immediately below for the
/// unary-scoped contrast, and the module doc's "PAST 2^64" paragraph for the remaining gap — values
/// `>= 2^64`, where the backends diverge by design rather than agree;
/// `past_the_u64_ceiling_the_backends_diverge_by_design` and `SATURATION_DEMOS` exercise exactly that,
/// on the TM side, in this file.
#[test]
fn native_runs_beyond_field_width() {
    for src in BEYOND_FIELD_WIDTH_DEMOS {
        assert_native_matches_reference(src);
    }
}

/// The TM's half of what `BEYOND_FIELD_WIDTH_DEMOS` claims. The ceiling is an outcome the caller can
/// see, so "native has no such ceiling" is a contrast between two measured results instead of a measured
/// result and an assertion in prose.
///
/// SCOPED TO UNARY: this pins `Unary::default()` specifically, not "the TM backend". Every value
/// in `BEYOND_FIELD_WIDTH_DEMOS` is « 2⁶⁴, so re-running this loop with `Binary::default()` in
/// place of `Unary::default()` would NOT overflow — the binary TM would agree with native and the
/// reference on all four. So this test demonstrates a real, measured gap, but it is "native vs.
/// unary", and the gap narrower than "native vs. the TM backend" would suggest — see
/// `crates/redextape-core/src/tm.rs`'s `TmRun::Overflow` doc
/// and `docs/superpowers/specs/2026-07-26-tm-binary-encoding-design.md`.
#[test]
fn the_tm_reports_its_ceiling_on_the_same_demos() {
    for src in BEYOND_FIELD_WIDTH_DEMOS {
        let core = core_of(src);
        assert!(
            matches!(run_tm(&core, &Unary::default(), TM_DEFAULT_CAPS), TmRun::Overflow),
            "the TM must REPORT that it cannot represent this, not miscompile it: {src}"
        );
    }
}

/// The other half of the module doc's claim that native's edge is "a contrast with UNARY, not with the
/// TM backend", as a measured result rather than a doc comment. Every value in
/// `BEYOND_FIELD_WIDTH_DEMOS` is « 2⁶⁴, so `Binary` represents all of them: it runs all four and agrees
/// with the reference (and so, transitively, with native — `native_runs_beyond_field_width` above pins
/// native against the same reference values).
///
/// Together with `the_tm_reports_its_ceiling_on_the_same_demos` (which MUST be kept — it is the
/// control), this establishes as two measured results the module doc's claim that the gap this file
/// exhibits is a contrast with UNARY, not with the TM backend.
#[test]
fn binary_runs_the_demos_unary_cannot_represent() {
    for src in BEYOND_FIELD_WIDTH_DEMOS {
        let reference = run(src).unwrap_or_else(|e| panic!("reference run failed for `{src}`: {e:?}"));
        let core = core_of(src);
        let (tm, enc) = tm_leg(&core, EncodingKind::Binary);
        match tm {
            TmRun::Ran { tapes } => assert_eq!(
                decode_tape(&tapes, &reference, &*enc),
                Some(reference.clone()),
                "binary-TM vs reference disagree for: {src}"
            ),
            other => panic!("binary must RUN what unary cannot represent, got {other:?} for: {src}"),
        }
    }
}

/// Native's ceiling-free claim at the ONE place it is genuinely load-bearing, and the TM's refusal
/// beside it. See `SATURATION_DEMOS` for why agreement is impossible here by construction.
///
/// The TM half loops over `encodings()` rather than naming `Binary`: this is a claim about the TM
/// BACKEND, not about one encoding, so a third encoding must satisfy it too the day it is added.
#[test]
fn past_the_u64_ceiling_the_backends_diverge_by_design() {
    for src in SATURATION_DEMOS {
        let reference = run(src).unwrap_or_else(|e| panic!("reference run failed for `{src}`: {e:?}"));
        assert_eq!(reference, Value::Nat(u64::MAX), "these demos exist in order to saturate: {src}");
        let core = core_of(src);
        match run_native(&core, DEFAULT_CAPS) {
            NativeRun::Ran(outcome) => assert_eq!(
                decode_rxm(&outcome, &reference),
                Some(reference.clone()),
                "native must saturate exactly as the reference does: {src}"
            ),
            other => panic!("native must run `{src}`, got {other:?}"),
        }
        for (name, kind) in encodings() {
            let (tm, _) = tm_leg(&core, kind);
            assert!(
                matches!(tm, TmRun::Overflow),
                "the {name} TM must REFUSE this, not saturate and not miscompile: {src} gave {tm:?}"
            );
        }
    }
}

/// Native reports the reference's words for each fault. The reference's text is its own code, apart
/// from the heap core native shares with the rxm interpreter, so a changed message fails here.
#[test]
fn faults_diverge_on_native() {
    for src in FAULT_DEMOS {
        let reference = run(src);
        let core = core_of(src);
        match (reference, run_native(&core, DEFAULT_CAPS)) {
            (Err(RunError::Runtime(e)), NativeRun::Fault(words)) => assert_eq!(words, e.message, "{src}"),
            (r, n) => panic!("expected reference Runtime + native Fault for {src}:\n  reference={r:?}\n  native={n:?}"),
        }
    }
}

// `arb_expr_below(1000)`:
// A first-order arithmetic/comparison/if expression generator, shape supplied by
// `redextape-test-support`'s `arb_expr_over`, shared with `redextape-core`'s `arb_expr_below(8)` in
// `three_way_oracle.rs` rather than reused from it. Unlike that generator native has NO
// `MAX_FIELD_WIDTH` bound, so leaves are widened to `0..1000` — native compiles to real 64-bit
// registers and never needs to stay under 64.
//
// `arb_tm_mixed_range_expr` (below) is this generator's STRUCTURAL TWIN — same `prop_recursive(3,
// 8, 3, ..)` parameters and operator set, a different leaf strategy. Both call `arb_expr_over`
// from `redextape-test-support`, so the shape exists once and the leaf is the only thing either
// supplies. Changing the recursion parameters or the arm set is a single edit there that
// necessarily reaches both.
proptest! {
    #![proptest_config(ProptestConfig { cases: 64, ..ProptestConfig::default() })]

    /// Random wide-range (no `MAX_FIELD_WIDTH` bound) arithmetic/comparison/if programs: `native ==
    /// reference` AND `native == rxm-interp`. The generator produces no loops/functions/faults, so a
    /// `HitCap`/`LowerError`/`Fault` would itself be a bug and trips the catch-all.
    #[test]
    fn native_agrees_with_reference_and_rxm_on_random_programs(src in arb_expr_below(1000)) {
        let reference = run(&src);
        let (prog, ds) = parse(&src);
        prop_assume!(ds.is_empty()); // skip anything that does not parse
        let core = desugar(&prog.unwrap());
        let native = run_native(&core, DEFAULT_CAPS);
        match (reference, native) {
            (Ok(rv), NativeRun::Ran(outcome)) => {
                prop_assert_eq!(decode_rxm(&outcome, &rv), Some(rv.clone()), "native vs reference disagree: {}", src);
                let lowered = lower_program(&core).expect("first-order arithmetic/if must lower to rxm");
                match run_rxm(&lowered, DEFAULT_CAPS) {
                    RxmRun::Ran(rxm_outcome) => {
                        prop_assert_eq!(decode_rxm(&rxm_outcome, &rv), Some(rv), "native vs rxm-interp disagree: {}", src);
                    }
                    other => prop_assert!(false, "rxm-interp did not run {}: {:?}", src, other),
                }
            }
            (r, n) => prop_assert!(false, "native mismatch for {}:\n  reference={:?}\n  native={:?}", src, r, n),
        }
    }
}

/// Same shape as `arb_expr_below(1000)` — both get it from `arb_expr_over`, whose own doc is the one
/// place the recursion parameters and arm set are written down. Restating them here would recreate, at
/// the doc layer, exactly the duplication that crate exists to remove: a copy that goes stale the day
/// the real parameters change in another crate.
///
/// What differs, and all this generator supplies, is a MIXED leaf: `prop_oneof!` over a small range
/// unary can represent (`0..8`, reused verbatim from
/// `redextape-core`'s `arb_expr_below(8)` in `three_way_oracle.rs` — that generator uses these exact
/// recursion parameters and its comment records a measured max value of 27 over 2M samples, well
/// under the 64-cell ceiling) and the wide `0..1000` range, weighted 4:1 toward the small range.
///
/// `arb_expr_below(1000)` keeps its pure `0..1000` leaves
/// (`native_agrees_with_reference_and_rxm_on_random_programs` depends on them); this is a separate
/// generator for the TM-legs proptest only.
///
/// Do not read `0..8` as "sitting at 64 minus a little room" — it is nowhere near the ceiling. The
/// headroom is the point: `+` on two leaves can exceed a bound either leaf alone satisfies, so the small
/// range has to stay far enough below 64 that a handful of small leaves summed together (this
/// generator's recursion can sum several) still lands under it. `0..8` is the same range
/// `arb_expr_below(8)` already proved safe under IDENTICAL recursion parameters, so reusing it verbatim
/// carries that proof over rather than re-deriving a new bound.
fn arb_tm_mixed_range_expr() -> impl Strategy<Value = String> {
    let small = 0u64..8;
    let wide = 0u64..1000;
    arb_expr_over(prop_oneof![4 => small, 1 => wide].prop_map(|n| n.to_string()))
}

proptest! {
    #![proptest_config(ProptestConfig { cases: 64, ..ProptestConfig::default() })]

    /// The TM legs over `arb_tm_mixed_range_expr` — and they are ASYMMETRIC BY NECESSITY, which is
    /// the whole reason this test has its own doc comment.
    ///
    /// THE NAME SAYS "AGREES" FOR BINARY AND "NEVER WRONG" FOR UNARY BECAUSE THOSE ARE DIFFERENT
    /// CLAIMS, not a stylistic choice: binary is asserted to decode equal to the reference on every
    /// case it runs, full agreement; unary is asserted only to never decode to a WRONG value when it
    /// runs, and is allowed to refuse (`Overflow`) instead. No improvement to unary's fire rate collapses
    /// that gap — "never wrong when it runs" stays strictly weaker than "agrees" no matter how often it
    /// runs — so the name states the asymmetric claim directly rather than relying on a reader to find
    /// it in the comment below.
    ///
    /// The generator mixes a small range unary can represent with the wide `0..1000` range a 64-cell
    /// UNARY field cannot. So:
    ///
    ///   * BINARY is a FULL leg: it must run, and decode equal to the reference.
    ///   * UNARY is asserted NEVER WRONG, which is strictly weaker: `Ran` must decode equal to the
    ///     reference; `Overflow` is permitted and still expected on a real fraction of cases (any leaf
    ///     drawn from the wide range, or an unlucky sum of small ones, can still overflow).
    ///
    /// DO NOT READ THE NAME AS SYMMETRIC. The unary half does not claim unary computes these programs.
    /// It claims unary never SILENTLY computes them wrongly — a `Ran` that decodes to the wrong value
    /// is caught, a refusal is not a failure. That is weaker than the binary leg, and it is stated rather
    /// than left for a reader to infer from the code.
    ///
    /// FIRE RATE: unary's `Ran` branch fired on ~60.4% of cases over 30 unseeded 64-case runs, with
    /// between 29 and 45 hits per run and none of the 30 runs seeing zero. So the unary half exercised
    /// its assertion on a clear majority of cases, on every run measured, rather than being live only
    /// in aggregate.
    #[test]
    fn binary_tm_agrees_while_unary_tm_is_never_wrong_on_random_programs(src in arb_tm_mixed_range_expr()) {
        let reference = run(&src);
        prop_assume!(reference.is_ok());
        let rv = reference.unwrap();
        let (prog, ds) = parse(&src);
        prop_assume!(ds.is_empty());
        let core = desugar(&prog.unwrap());

        let (btm, benc) = tm_leg(&core, EncodingKind::Binary);
        match btm {
            TmRun::Ran { tapes } => prop_assert_eq!(
                decode_tape(&tapes, &rv, &*benc),
                Some(rv.clone()),
                "binary-TM vs reference disagree: {}",
                src
            ),
            other => prop_assert!(false, "binary must run {}: {:?}", src, other),
        }

        // The weaker half. A refusal is fine; a WRONG ANSWER is not.
        let (utm, uenc) = tm_leg(&core, EncodingKind::Unary);
        if let TmRun::Ran { tapes } = utm {
            prop_assert_eq!(
                decode_tape(&tapes, &rv, &*uenc),
                Some(rv.clone()),
                "unary-TM RAN and produced the WRONG answer: {}",
                src
            );
        }
    }
}

/// The 60.4% figure in `binary_tm_agrees_while_unary_tm_is_never_wrong_on_random_programs`'s doc is
/// LOAD-BEARING: it is the whole reason that test's unary half is not near-vacuous.
///
/// A leaf-range or weight edit that walked that back would otherwise leave the doc comment simply
/// false. This pins a FLOOR, deterministically (fixed RNG, so it cannot flake), well below the
/// measured value: the point is to catch a regression to near-zero, not to pin 60.4% exactly, which
/// would break on any legitimate retuning.
#[test]
fn the_unary_leg_of_the_random_test_actually_fires() {
    use proptest::strategy::{Strategy, ValueTree};
    use proptest::test_runner::{Config, RngAlgorithm, TestRng, TestRunner};

    const SAMPLES: usize = 200;
    // 30% of SAMPLES. TWO measurements, deliberately distinguished because they come from different
    // sampling and a reader should not have to guess which this floor is set against: the neighbouring
    // proptest's doc records ~60.4% (1920 cases across 30 RANDOMISED runs), while THIS test's own
    // fixed-seed run measures 126/200 = 63.0%. The floor sits far below both and far above the 1/200
    // (0.5%) the sabotage produces, so it discriminates the two regimes under either figure.
    const FLOOR: usize = 60;

    let mut runner = TestRunner::new_with_rng(Config::default(), TestRng::deterministic_rng(RngAlgorithm::ChaCha));
    let strat = arb_tm_mixed_range_expr();
    let mut ran = 0usize;
    for _ in 0..SAMPLES {
        let src = strat.new_tree(&mut runner).expect("generator produces a value").current();
        let core = core_of(&src);
        if matches!(tm_leg(&core, EncodingKind::Unary).0, TmRun::Ran { .. }) {
            ran += 1;
        }
    }
    assert!(
        ran >= FLOOR,
        "the unary leg ran on only {ran}/{SAMPLES} generated programs (floor {FLOOR}); the mixed-range \
         generator's small-leaf weight was probably reduced, which would make the ~60.4% figure in \
         `binary_tm_agrees_while_unary_tm_is_never_wrong_on_random_programs`'s doc comment false"
    );
}
