#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic, clippy::pedantic)]
#![cfg(feature = "cranelift")]
//! The native oracle: for every first-order demo, the reference tree-walker's value, the decoded λ
//! normal form, the decoded TM final tape UNDER EVERY ENCODING, and the decoded native (Cranelift JIT)
//! result all agree. This extends `redextape-core`'s three-way oracle (`tests/three_way_oracle.rs`)
//! with native as a validated leg.
//!
//! Native's PRIMARY new cross-check is narrower and sharper than the four-way: `native == rxm-interp`
//! on the SAME lowered `Program` isolates codegen (`run_native`/Cranelift) from interpretation
//! (`run_rxm`) — both share `lower_rxm`/`defunc`, so any disagreement is a real codegen bug, not a
//! front-end or lowering difference.
//!
//! ONE TEST PER ENCODING, not one test doing every encoding: `four_way_tests!` emits
//! `four_way_oracle_on_the_first_order_suite_{unary,binary}`, so each emitted test is still genuinely
//! FOUR-way (reference == λ == TM(one encoding) == native) and its name states its real arity. It is
//! this FILE that covers five legs — reference, λ, TM-unary, TM-binary, native — not any single test.
//! LEGS, not "backends": two of the five are the same TM backend at different encodings, the
//! distinction this file polices elsewhere (`the_tm_reports_its_ceiling_on_the_same_demos`'s "SCOPED TO
//! UNARY" note, `past_the_u64_ceiling_the_backends_diverge_by_design`'s "a claim about the TM BACKEND,
//! not about one encoding").
//!
//! WHAT ACTUALLY FORCES A DEVELOPER HERE, stated precisely rather than implied end-to-end: adding a
//! third `EncodingKind` breaks `tm_leg`'s match below (no wildcard arm) at COMPILE TIME, and that is
//! one forcing function — the new arm is required to compile, so an edit to THIS FILE is
//! unavoidable. `encodings()` (below) DERIVES from `EncodingKind::ALL`, generated by the same
//! `encoding_kinds!` invocation (`tm/header.rs`) that declares the variants, so a new row reaches
//! `encodings()` without anyone editing THAT FUNCTION — which is a narrower claim than "without
//! editing this file", and the narrower one is the true one. `every_encoding_has_a_four_way_test`
//! derives its expectation from `encodings()` AT RUNTIME and compares it against `EMITTED`, so it
//! catches drift BETWEEN THOSE TWO LISTS — a generated test deleted, or the `four_way_tests!`
//! invocation below left stale. `encodings()` cannot itself fall behind `EncodingKind::ALL`: the
//! chain from a new row in `encoding_kinds!` to this file's coverage guard is closed end to end, so
//! the one thing still requiring a developer's hand here is the `four_way_tests!` macro invocation
//! itself — see `every_encoding_has_a_four_way_test`'s own doc comment below for the same statement
//! at its point of use.
//!
//! THE UNARY LEG RUNS AT THE FIXED `MAX_FIELD_WIDTH` (64), while binary goes through `run_tm_fitted`.
//! The asymmetry is DELIBERATE CONVENTION, not a correctness requirement — see `tm_leg`'s doc comment
//! below for the full statement and its citation.
//!
//! Two things `tm_leg`'s doc does not cover, both about why UNARY in particular stays fixed rather than
//! also being fitted (considered and rejected, so a future editor does not "fix" it): fitting unary
//! would silently move every demo from a 64-cell bank to an 8-16-cell one, a LATERAL coverage change
//! (fitted exercises narrow banks and the overflow boundary; fixed-64 exercises wide banks — neither
//! dominates). And the width axis itself is not this file's job: `tm_width_equivalence.rs` and
//! `tm_bank_invariant.rs` already own it, running `widths() x encodings_at(width)` deliberately across
//! the full range; this file checks native agreement at one width per encoding, the same split core's
//! `three_way_oracle.rs` uses.
//!
//! NATIVE'S DISTINCTIVE CAPABILITY, stated at the width it actually holds. Native compiles to real
//! 64-bit machine registers and has no `MAX_FIELD_WIDTH` ceiling. That is a contrast with UNARY, not
//! with the TM backend: a `w`-cell binary field holds `0..2^w`, so at 64 cells `Binary` covers the
//! entire `u64` range. Both halves are MEASURED rather than asserted in prose —
//! `the_tm_reports_its_ceiling_on_the_same_demos` pins unary reporting `Overflow` on
//! `BEYOND_FIELD_WIDTH_DEMOS` (the control), and `binary_runs_the_demos_unary_cannot_represent` pins
//! binary running the same four and agreeing with the reference.
//!
//! PAST 2^64 THE BACKENDS DIVERGE BY DESIGN, and that is pinned rather than left unexercised — see
//! `past_the_u64_ceiling_the_backends_diverge_by_design` and `SATURATION_DEMOS`. It cannot be an
//! agreement test: the reference and native SATURATE to `u64::MAX` (the
//! `saturating_add`/`saturating_mul` in `tm/rxm.rs`), while the TM halts in the rule-less
//! overflow-guard state `tm/build.rs`'s `Builder::overflow` allocates, at every width up to the
//! ceiling. Both are deliberate.
//!
//! CAPS NOTE: native's step accounting is coarse (it ticks only loop back-edges and bounds calls by depth, enough to
//! guarantee termination, not to match `run_rxm`'s per-instruction step count). Every program here uses
//! `DEFAULT_CAPS`/`TM_DEFAULT_CAPS` (generous) and terminates well within them, so a tight cap never
//! produces a spurious cross-backend "disagreement".

